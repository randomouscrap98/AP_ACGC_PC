# Shellsanity beach item texture: pc/res/ap_shell.png (16x16, drawn by hand 2026-10-15) as a CI4
# texture in the shell's own format, written as pc/src/pc_ap_beach_logo.c (texture, palette, material
# display list).
# Run: uv run --with pillow python pc/tools/ap/gen_ap_logo.py [--check | --preview out.png]
# (--check: exit 1 if the file is out of date, write nothing; run by gen_all.sh)
#
# Transparent: alpha < 128, or the sand colour the image was drawn on (SAND). At most 15 other colours
# (CI4 = 16 entries, index 0 transparent). The material is a cutout (G_RM_AA_ZB_TEX_EDGE2), no blending.
# Before 2026-10-15 this shrank and shaded the Archipelago icon (git history of this file).
import os
import sys

from PIL import Image

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../.."))
SRC = REPO + "/pc/res/ap_shell.png"
OUT = REPO + "/pc/src/pc_ap_beach_logo.c"
SAND = (214, 196, 150)


def load():
    # 16x16 RGB colours, None = transparent
    im = Image.open(SRC).convert("RGBA")
    if im.size != (16, 16):
        sys.exit("%s must be 16x16, is %dx%d" % (SRC, im.size[0], im.size[1]))
    out = []
    for r, g, b, a in im.get_flattened_data():
        out.append(None if a < 128 or (r, g, b) == SAND else (r, g, b))
    return out


def rgb5a3(r, g, b):
    # opaque RGB555 with the top bit set
    return 0x8000 | (r >> 3) << 10 | (g >> 3) << 5 | (b >> 3)


def encode_ci4(idx):
    # 16x16 indices (row-major) -> GC CI4: 8x8 tiles, row-major tiles, 2 pixels per byte, high nibble first
    out = bytearray()
    for ty in range(0, 16, 8):
        for tx in range(0, 16, 8):
            for y in range(8):
                for x in range(0, 8, 2):
                    a = idx[(ty + y) * 16 + tx + x]
                    b = idx[(ty + y) * 16 + tx + x + 1]
                    out.append(a << 4 | b)
    return bytes(out)


def build():
    out = load()
    colours = sorted(set(c for c in out if c))
    if len(colours) > 15:
        sys.exit("%s has %d colours, CI4 allows 15 (+ transparent)" % (SRC, len(colours)))
    pal = [0x0000] + [rgb5a3(*c) for c in colours]  # index 0: transparent (alpha 0)
    pal += [0x8000] * (16 - len(pal))
    idx = [colours.index(c) + 1 if c else 0 for c in out]
    return pal, idx, encode_ci4(idx)


def make_c(pal, tex):
    pal_s = ", ".join("0x%04X" % v for v in pal)
    tex_lines = []
    for i in range(0, len(tex), 16):
        tex_lines.append("    " + ", ".join("0x%02X" % b for b in tex[i:i + 16]) + ",")
    src = f"""// GENERATED by pc/tools/ap/gen_ap_logo.py from pc/res/ap_shell.png, do not edit.
// Shellsanity beach item: the shell A material (obj_item_shellAT_mat_model) with the Archipelago
// icon as texture. Drawn with the shell's quad (obj_item_shellAT_gfx_model); see pc_ap_beach_draw.c_inc.
#include "libforest/gbi_extensions.h"
#include "PR/gbi.h"

// RGB5A3, native order (like disc palettes after the asset loader's u16 swap); index 0 transparent
static u16 pc_ap_beach_pal[16] ATTRIBUTE_ALIGN(32) = {{ {pal_s} }};

// CI4 16x16, GC tile order
static u8 pc_ap_beach_tex[0x80] ATTRIBUTE_ALIGN(32) = {{
{chr(10).join(tex_lines)}
}};

Gfx pc_ap_beach_mat_model[] = {{
    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_ON),
    gsDPSetRenderMode(G_RM_FOG_SHADE_A, G_RM_AA_ZB_TEX_EDGE2),
    gsDPSetCombineLERP(TEXEL0, 0, SHADE, 0, 0, 0, 0, TEXEL0, PRIMITIVE, 0, COMBINED, 0, 0, 0, 0, COMBINED),
    gsDPLoadTLUT_Dolphin(15, 16, 1, pc_ap_beach_pal),
    gsDPSetTextureImage_Dolphin(G_IM_FMT_CI, G_IM_SIZ_4b, 16, 16, pc_ap_beach_tex),
    gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE, 0, 15, GX_CLAMP, GX_CLAMP, 0, 0),
    gsDPSetPrimColor(0, 128, 255, 255, 255, 255),
    gsSPLoadGeometryMode(G_ZBUFFER | G_SHADE | G_CULL_BACK | G_FOG | G_LIGHTING | G_SHADING_SMOOTH | G_DECAL_LEQUAL),
    gsSPEndDisplayList(),
}};
"""
    return src


def preview(pal, idx, path):
    # decode back through the same formats (inverse of the above) onto sand
    im = Image.new("RGBA", (16, 16), (214, 196, 150, 255))
    for i, c in enumerate(idx):
        v = pal[c]
        if v & 0x8000:
            im.putpixel((i % 16, i // 16), ((v >> 10 & 31) * 255 // 31, (v >> 5 & 31) * 255 // 31, (v & 31) * 255 // 31, 255))
    im.resize((256, 256), Image.NEAREST).save(path)


if __name__ == "__main__":
    pal, idx, tex = build()
    src = make_c(pal, tex)
    if sys.argv[1:2] == ["--check"]:
        ok = os.path.exists(OUT) and open(OUT).read() == src
        print(("  ok   " if ok else "  FAIL ") + "pc/src/pc_ap_beach_logo.c up to date (gen_ap_logo.py)")
        sys.exit(0 if ok else 1)
    with open(OUT, "w") as f:
        f.write(src)
    print("wrote", OUT)
    if len(sys.argv) == 3 and sys.argv[1] == "--preview":
        preview(pal, idx, sys.argv[2])

#!/usr/bin/env python3
# Names for the sound test (--sound-test): every NA_SE_* and BGM_* enum entry in include/audio_defs.h.
# Writes pc/src/pc_sound_test_names.c. The table holds the enum identifiers themselves, so the compiler
# works out their values (no value parsing here).
# Usage: gen_sound_names.py [--check]   (--check: exit 1 if the file is out of date, write nothing)
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
SRC = os.path.join(ROOT, "include", "audio_defs.h")
OUT = os.path.join(ROOT, "pc", "src", "pc_sound_test_names.c")


def enum_names(text, prefix):
    return re.findall(r"^\s*(" + prefix + r"\w+)\s*(?:=[^,]*)?,", text, re.M)


def table(name, names):
    lines = [f"const pc_sound_test_name {name}[] = {{"]
    lines += [f'  {{ {n}, "{n}" }},' for n in names]
    lines.append("};")
    lines.append(f"const int {name}_count = {len(names)};")
    return lines


def render():
    with open(SRC) as f:
        text = f.read()
    se = enum_names(text, "NA_SE_")
    bgm = enum_names(text, "BGM_")
    assert len(se) > 200 and len(bgm) > 150, (len(se), len(bgm))
    lines = [
        "// Generated by pc/tools/ap/gen_sound_names.py from include/audio_defs.h. Don't edit.",
        '#include "pc_sound_test.h"',
        '#include "audio_defs.h"',
        "",
    ]
    lines += table("pc_sound_test_se_names", se)
    lines.append("")
    lines += table("pc_sound_test_bgm_names", bgm)
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        with open(OUT) as f:
            same = f.read() == text
        print(f"  {'ok  ' if same else 'FAIL'} pc/src/pc_sound_test_names.c up to date (gen_sound_names.py)")
        sys.exit(0 if same else 1)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()

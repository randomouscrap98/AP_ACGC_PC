#!/usr/bin/env python3
# Writes apworld/animal_crossing/catalog_data.py: the Catalogsanity eligible items, from the decomp's shop lists
# A/B/C (src/data/item/*_list.c) minus fixed hand-outs and the froggy chair. Diaries are left out: only Nook
# sells them, and only from Nookway (decided 2026-10-12). Stationery is left out too: letters register their
# paper when read and the Nook job gives PAPER55 (leak sweep, decided 2026-10-13).
# Usage: gen_catalog_data.py [--check]   (--check: exit 1 if the file is out of date, write nothing)
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(ROOT, "apworld", "animal_crossing", "catalog_data.py")


def read(path):
    with open(os.path.join(ROOT, path)) as f:
        return f.read()


ftr_enum = re.search(r"enum ftr_name \{(.*?)\};", read("include/m_ftr_def.h"), re.S).group(1)
FTR_NAMES = [l.strip().rstrip(",") for l in ftr_enum.splitlines() if l.strip().startswith("FTR_")]
FTR_IDX = {n: i for i, n in enumerate(FTR_NAMES)}


def ftr_no(name):
    # FTR_START(name): FTR0 0x1000 + idx*4, FTR1 0x3000 + (idx - 0x400)*4
    i = FTR_IDX[name]
    return 0x1000 + (i << 2) if i < 0x400 else 0x3000 + ((i - 0x400) << 2)


def abc_list(path, prefix):
    # Ids of lists A/B/C in one *_list.c, in file order
    text = read(path)
    ids = []
    for tier in "ABC":
        body = re.search(prefix + tier + r"\[\] = \{(.*?)\};", text, re.S).group(1)
        for ftr, num in re.findall(r"FTR_START\((\w+)\)|(0x[0-9A-Fa-f]+)", body):
            ids.append(ftr_no(ftr) if ftr else int(num, 16))
    return ids


# Fixed hand-outs that are in A/B/C (research/catalog.md), plus the froggy chair (kept for a later goal)
EXCLUDED = (
    [0x2400 + n for n in range(16)]                                     # starting shirts CLOTH000-015
    + [0x2400 + n for n in (105, 108, 109, 110, 144, 145, 156)]         # mom (m_private.c:1002-1010)
    + [ftr_no(n) for n in ("FTR_SUM_CASSE01", "FTR_NOG_MIKANBOX", "FTR_SUM_DOLL02")]  # start, mom
    + [0x2700 + n for n in (3, 41, 55, 42)]                             # house walls (m_home.c:312)
    + [0x2600 + n for n in (38, 42, 5, 34)]                             # house floors
    + [ftr_no("FTR_ARI_ISU01")]                                         # froggy chair
    + [0x2400 + 226]                                                    # inventory background (m_private.c:148)
)

CATEGORIES = [
    ("furniture", abc_list("src/data/item/ftr_list.c", "ftr_list")),
    ("clothes", abc_list("src/data/item/cloth_list.c", "cloth_list")),
    ("carpet", abc_list("src/data/item/carpet_list.c", "carpet_list")),
    ("wallpaper", abc_list("src/data/item/wall_list.c", "wall_list")),
]


def render():
    all_ids = [i for _, ids in CATEGORIES for i in ids]
    assert len(all_ids) == len(set(all_ids)) == 611, len(all_ids)
    assert all(i in all_ids for i in EXCLUDED), [hex(i) for i in EXCLUDED if i not in all_ids]
    lines = [
        "# Generated by pc/tools/ap/gen_catalog_data.py from the decomp's shop lists. Don't edit.",
        "# Catalogsanity eligible items (game item ids, as the shops hand them out): lists A/B/C minus fixed",
        "# hand-outs (starting shirts, mom, house walls/floors, starting furniture, inventory background) and",
        "# the froggy chair. No diaries (only Nook sells them, from Nookway) and no stationery (letters register",
        "# their paper when read).",
        "",
        "CATALOG_ITEMS = {",
    ]
    total = 0
    for name, ids in CATEGORIES:
        keep = sorted(i for i in ids if i not in EXCLUDED)
        total += len(keep)
        lines.append(f"    \"{name}\": [")
        for k in range(0, len(keep), 10):
            lines.append("        " + " ".join(f"0x{i:04x}," for i in keep[k:k + 10]))
        lines.append("    ],")
    lines.append("}")
    assert total == 575, total
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        with open(OUT) as f:
            same = f.read() == text
        print(f"  {'ok  ' if same else 'FAIL'} catalog_data.py up to date (gen_catalog_data.py)")
        sys.exit(0 if same else 1)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()

OUTLINE = True  # the darker same-colour outline around each mark (off tried 2026-10-20: worse)
HALF = 1200  # quad half size in model units (bg_item draws at 0.01 scale: 24 world units, 60% of a square)


def encode_ia4(art):
    # 16x16 rows -> GC IA4 (8 bpp: alpha high nibble, intensity low): 8x4 tiles, row-major tiles.
    # Fill: white (the prim colour tints it), outline: intensity 8/15 = a darker shade of the same colour, both
    # opaque before the prim alpha
    assert len(art) == 16 and all(len(r) == 16 for r in art)
    fill = lambda x, y: 0 <= x < 16 and 0 <= y < 16 and art[y][x] == "#"
    px = [[0] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            if fill(x, y):
                px[y][x] = 0xFF
            elif OUTLINE and any(fill(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1)):
                px[y][x] = 0xF8
    out = bytearray()
    for ty in range(0, 16, 4):
        for tx in range(0, 16, 8):
            for y in range(4):
                for x in range(8):
                    out.append(px[ty + y][tx + x])
    return bytes(out)


def tex_c(name, data):
    lines = ["    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    return "static u8 %s[0x100] ATTRIBUTE_ALIGN(32) = {\n%s\n};\n" % (name, "\n".join(lines))


def mat_c(name, tex):
    return f"""Gfx {name}[] = {{
    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_ON),
    gsDPSetCombineLERP(TEXEL0, 0, PRIMITIVE, 0, TEXEL0, 0, PRIMITIVE, 0, 0, 0, 0, COMBINED, 0, 0, 0, COMBINED),
    gsDPSetRenderMode(G_RM_FOG_SHADE_A, G_RM_AA_ZB_XLU_DECAL2),
    gsDPSetTextureImage_Dolphin(G_IM_FMT_IA, G_IM_SIZ_8b, 16, 16, {tex}),
    gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE, 0, 15, GX_CLAMP, GX_CLAMP, 0, 0),
    gsSPLoadGeometryMode(G_ZBUFFER | G_SHADE | G_FOG | G_SHADING_SMOOTH | G_DECAL_LEQUAL),
    gsSPEndDisplayList(),
}};
"""



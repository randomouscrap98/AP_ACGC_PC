# Writes apworld/animal_crossing/villager_data.py: every villager that can live in town
# (starter or move-in; islanders skipped), with npc index, name and personality.
# Names come from the ROM (npc_name_str_table.bin, 8 bytes per npc index),
# personality from npc_looks_table (src/game/m_name_table.c),
# eligibility from npc_grow_list (src/data/npc/grow_list.c).
# usage: python3 dump_villagers.py [--check]   (--check: exit 1 if the file is out of date, write nothing)
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_msg as dm

REPO = dm.REPO
NPC_NUM = 236
NAME_LEN = 8
# mNpc_LOOKS_* order (include/m_npc_personal_id.h)
LOOKS = ["GIRL", "KO_GIRL", "BOY", "SPORT_MAN", "GRIM_MAN", "NANIWA_LADY"]
PERSONALITIES = ["Normal", "Peppy", "Lazy", "Jock", "Cranky", "Snooty"]
OUT = os.path.join(REPO, "apworld", "animal_crossing", "villager_data.py")


def c_array(path, name, prefix):
    src = open(os.path.join(REPO, path)).read()
    body = re.search(name + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    return re.findall(prefix + r"(\w+)", body)


looks = c_array("src/game/m_name_table.c", "npc_looks_table", "mNpc_LOOKS_")
grow = c_array("src/data/npc/grow_list.c", "npc_grow_list", "mNpc_GROW_")
assert len(grow) >= NPC_NUM, len(grow)
assert len(looks) >= NPC_NUM, len(looks)

names_bin = dm.res("forest_2nd.arc", "npc_name_str_table.bin")
assert len(names_bin) == NPC_NUM * NAME_LEN, len(names_bin)

rows = []
for i in range(NPC_NUM):
    if grow[i] not in ("STARTER", "MOVE_IN"):
        continue
    name = dm.decode(names_bin[i * NAME_LEN:(i + 1) * NAME_LEN], False).rstrip()
    assert re.fullmatch(r"[A-Za-z .'-]+", name), (i, name)
    rows.append((i, name, LOOKS.index(looks[i])))

names = [r[1] for r in rows]
assert len(set(names)) == len(names), "duplicate villager names"

text = ("# Generated by pc/tools/ap/dump_villagers.py, don't edit by hand.\n"
        "# Villagers that can live in town (islanders excluded): name -> (npc index, personality).\n"
        "# npc index = npc_id - NPC_START; personality = mNpc_LOOKS_* (index into PERSONALITIES).\n\n"
        + "PERSONALITIES = [%s]\n\n" % ", ".join('"%s"' % p for p in PERSONALITIES)
        + "VILLAGERS = {\n"
        + "".join('    "%s": (%d, %d),\n' % (name, i, look) for i, name, look in rows)
        + "}\n")

if "--check" in sys.argv:
    same = open(OUT, newline="").read() == text
    print(f"  {'ok  ' if same else 'FAIL'} apworld/animal_crossing/villager_data.py up to date (dump_villagers.py)")
    sys.exit(0 if same else 1)
with open(OUT, "w", newline="\n") as f:
    f.write(text)
print("%d villagers -> %s" % (len(rows), OUT))

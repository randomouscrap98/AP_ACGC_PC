#!/usr/bin/env python3
"""Generate pc/include/pc_vk_pipeline_seed.h from vulkan_pipelines.bin files.

The seed lists Vulkan pipelines the game creates at startup (Settings "Precompile shaders"), so a fresh install
doesn't stutter the first time an effect shows up. The game appends every pipeline the seed doesn't have to
vulkan_pipelines.bin next to the exe; collect those (play sessions, render scenes) and merge them in:

    python3 pc/tools/gen_vk_pipeline_seed.py path/to/vulkan_pipelines.bin [more.bin ...]

Keeps the existing seed's records (unless the record size changed). Record layout: pc_gx_sdl.c (REC_*).
"""
import os
import re
import struct
import sys

MAGIC = 0x50564341  # ACVP
HEADER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "include", "pc_vk_pipeline_seed.h")


def read_seed(path, rec_size):
    try:
        text = open(path).read()
    except OSError:
        return []
    m = re.search(r"#define PC_VK_PIPELINE_SEED_REC_SIZE (\d+)", text)
    count = re.search(r"#define PC_VK_PIPELINE_SEED_COUNT (\d+)", text)
    if not m or int(m.group(1)) != rec_size or not count:
        print("note: existing seed has another record size, dropping its records")
        return []
    rows = [bytes(int(b) for b in row.split(",")) for row in re.findall(r"^    \{([\d,]+)\},$", text, re.M)]
    return rows[:int(count.group(1))]  # an empty seed has one placeholder row


def read_bin(path):
    data = open(path, "rb").read()
    magic, rec_size = struct.unpack_from("<II", data)
    if magic != MAGIC:
        sys.exit("%s: not a vulkan_pipelines.bin" % path)
    body = data[8:]
    return rec_size, [body[i:i + rec_size] for i in range(0, len(body) - rec_size + 1, rec_size)]


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    rec_size = None
    new = []
    for path in sys.argv[1:]:
        size, recs = read_bin(path)
        if rec_size is not None and size != rec_size:
            sys.exit("%s: record size %d, others %d" % (path, size, rec_size))
        rec_size = size
        new += recs
    recs = []
    for r in read_seed(HEADER, rec_size) + new:
        if r not in recs:
            recs.append(r)
    rows = ["    {%s}," % ",".join(str(b) for b in r) for r in recs] or ["    {0},"]
    with open(HEADER, "w") as f:
        f.write("/* Auto-generated by pc/tools/gen_vk_pipeline_seed.py - do not edit.\n"
                " * Vulkan pipelines precompiled at startup (pc_gx_sdl.c), record layout in that file. */\n"
                "#ifndef PC_VK_PIPELINE_SEED_H\n#define PC_VK_PIPELINE_SEED_H\n\n"
                "#define PC_VK_PIPELINE_SEED_REC_SIZE %d\n#define PC_VK_PIPELINE_SEED_COUNT %d\n\n"
                "static const unsigned char pc_vk_pipeline_seed[][PC_VK_PIPELINE_SEED_REC_SIZE] = {\n%s\n};\n\n"
                "#endif\n" % (rec_size, len(recs), "\n".join(rows)))
    print("%d pipelines in %s" % (len(recs), os.path.normpath(HEADER)))


if __name__ == "__main__":
    main()

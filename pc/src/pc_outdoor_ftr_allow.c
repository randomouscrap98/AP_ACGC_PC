int pc_outdoor_ftr_allowed(u16 ftr_no) {
  const aFTR_PROFILE* profile = aMR_pc_GetProfile(ftr_no);

  if(profile == NULL || profile->vtable == NULL) {
    return FALSE;
  }
  for(unsigned i = 0; i < sizeof(pc_outdoor_ftr_allow_list) / sizeof(pc_outdoor_ftr_allow_list[0]); i++) {
    if(pc_outdoor_ftr_allow_list[i] == profile) {
      return TRUE;
    }
  }
  return FALSE;
}
